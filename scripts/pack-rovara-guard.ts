// Packs the model proxy's guard (docs/learnings/model-sources-spike/rovara_guard.py) into packages/model-proxy/src/rovara-guard-packed.ts: the guard deflated and base64-encoded, and its SHA-256.
// The proxy's task definition carries the packed form (about 16 KB) instead of the 40 KB text, and the container unpacks it to a file and checks the SHA-256 before it starts LiteLLM.
// The packed text is committed, not made at synth, so a template never depends on the zlib build of the machine that synthesizes it; tests/contract/rovara-guard.test.ts fails when the spike's
// file and the packed module drift apart. Run again after any change to the guard:  node scripts/pack-rovara-guard.ts
// Node runs this file directly, so only erasable syntax.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { deflateSync } from "node:zlib";

const source = new URL("../docs/learnings/model-sources-spike/rovara_guard.py", import.meta.url);
const target = new URL("../packages/model-proxy/src/rovara-guard-packed.ts", import.meta.url);
const guard = readFileSync(source);
const packed = deflateSync(guard, { level: 9 }).toString("base64");
const sha256 = createHash("sha256").update(guard).digest("hex");
const header = [
  "// GENERATED by scripts/pack-rovara-guard.ts from docs/learnings/model-sources-spike/rovara_guard.py. Do not edit: run `node scripts/pack-rovara-guard.ts` after a change to the guard.",
  "// The guard as the proxy's task definition carries it: zlib-deflated (level 9), then base64. The container unpacks it, checks it against ROVARA_GUARD_SHA256, and only then starts LiteLLM.",
];
writeFileSync(target, `${header.join("\n")}\nexport const ROVARA_GUARD_SHA256 = ${JSON.stringify(sha256)};\nexport const ROVARA_GUARD_PACKED = ${JSON.stringify(packed)};\n`);
process.stdout.write(`packed ${String(guard.length)} bytes into ${String(packed.length)} base64 characters, sha256 ${sha256}\n`);
