// Regenerates packages/cloud-contracts/src/generated/test-access-scoping.ts, the customer test account's per-action scoping table (lane TA1).
//
//   npx tsx scripts/test-access/gen-action-scoping.ts --download <dir>                          fetch AWS's Service Authorization Reference (public JSON over HTTPS; no AWS account, no AWS API) into <dir>
//   npx tsx scripts/test-access/gen-action-scoping.ts --from <dir> --services <table.json>      write the table; <table.json> is Rovara Code's generated/aws-emulator-services.json (the services Rovara local AWS serves)
//   add --check to compare with the committed file instead of writing it
//
// A service key maps to an IAM prefix by its SigV4 signing name, then its key, endpoint prefix, boto3 name and lower-cased SDK id, the first the reference knows. SERVICE_KEY_PREFIX_OVERRIDES covers the ones those miss.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { encodeScopingRow } from "../../packages/cloud-contracts/src/test-access-scoping.js";
import { scopingRows, type ReferenceService } from "./classify.js";

const INDEX_URL = "https://servicereference.us-east-1.amazonaws.com/";
const OUTPUT = "packages/cloud-contracts/src/generated/test-access-scoping.ts";

/** Keys whose names do not match a reference prefix: the IAM prefix the service's actions use. */
export const SERVICE_KEY_PREFIX_OVERRIDES: Readonly<Record<string, string>> = {
  "iot-data-plane": "iot",
  "iot-jobs-data-plane": "iotjobsdata",
  iotsecuretunneling: "iot",
  mturk: "mechanicalturk",
  "resource-groups-tagging-api": "tag",
  cloudcontrol: "cloudformation",
};

interface TableRow {
  readonly key: string;
  readonly signingName: string | null;
  readonly endpointPrefix: string | null;
  readonly boto3Name: string;
  readonly sdkId: string;
}

export function iamPrefixFor(row: TableRow, known: ReadonlySet<string>): string | undefined {
  const override = SERVICE_KEY_PREFIX_OVERRIDES[row.key];
  if (override !== undefined) return known.has(override) ? override : undefined;
  const candidates = [row.signingName, row.key, row.endpointPrefix, row.boto3Name, row.sdkId.toLowerCase().replaceAll(" ", "")];
  return candidates.find((candidate): candidate is string => candidate !== null && known.has(candidate));
}

async function download(directory: string): Promise<void> {
  mkdirSync(join(directory, "svc"), { recursive: true });
  const index = (await (await fetch(INDEX_URL)).json()) as { service: string; url: string }[];
  writeFileSync(join(directory, "index.json"), JSON.stringify(index));
  for (const { service, url } of index) {
    const response = await fetch(url);
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
    writeFileSync(join(directory, "svc", `${service}.json`), await response.text());
  }
}

function build(directory: string, tablePath: string): string {
  const index = JSON.parse(readFileSync(join(directory, "index.json"), "utf8")) as { service: string; modified?: number }[];
  const known = new Set(index.map((entry) => entry.service));
  const table = JSON.parse(readFileSync(tablePath, "utf8")) as { engine: string; services: TableRow[] };
  const keyToPrefix: Record<string, string> = {};
  const unmapped: string[] = [];
  for (const row of table.services) {
    const prefix = iamPrefixFor(row, known);
    if (prefix === undefined) unmapped.push(row.key);
    else keyToPrefix[row.key] = prefix;
  }
  const prefixes = [...new Set(Object.values(keyToPrefix))].sort();
  const services: Record<string, Record<string, string[]>> = {};
  const nameArns: Record<string, readonly string[]> = {};
  let versions = new Set<string>();
  for (const prefix of prefixes) {
    const reference = JSON.parse(readFileSync(join(directory, "svc", `${prefix}.json`), "utf8")) as ReferenceService & { Version?: string };
    if (reference.Version !== undefined) versions = versions.add(reference.Version);
    const grouped: Record<string, string[]> = {};
    const scoping = scopingRows(reference, prefix);
    for (const [action, row] of Object.entries(scoping.rows)) (grouped[encodeScopingRow(row)] ??= []).push(action);
    if (scoping.nameArns.length > 0) nameArns[prefix] = scoping.nameArns;
    for (const actions of Object.values(grouped)) actions.sort();
    services[prefix] = Object.fromEntries(Object.entries(grouped).sort(([a], [b]) => (a < b ? -1 : 1)));
  }
  const modified = Math.max(...index.filter((entry) => prefixes.includes(entry.service)).map((entry) => entry.modified ?? 0));
  const source = {
    reference: INDEX_URL,
    referenceVersions: [...versions].sort(),
    referenceModified: new Date(modified * 1000).toISOString(),
    serviceTable: table.engine,
  };
  const stringify = (value: unknown): string => JSON.stringify(value);
  const lines = [
    "// GENERATED by scripts/test-access/gen-action-scoping.ts. Do not edit; change the generator or its inputs and run it again.",
    "//",
    "// Source: AWS Service Authorization Reference (machine-readable), https://servicereference.us-east-1.amazonaws.com/ (documented at https://docs.aws.amazon.com/service-authorization/latest/reference/reference.html),",
    `// for the services of ${table.engine}. Each IAM prefix lists its changing actions grouped under a 5-character code (decode with decodeScopingRow in ../test-access-scoping.ts):`,
    "//   kind c create, w write, d delete, t tagging only, p permissions management | guard t tag, n name, s signer only | q = aws:RequestTag supported | resource tag coverage a all, p part, - none | name coverage a all, p part, - none",
    "// Reads and lists are left out. The kind is a verb heuristic (the reference only says write); the signer classifies for itself.",
    "",
    `export const TEST_ACCESS_SCOPING_SOURCE = ${stringify(source)} as const;`,
    "",
    "/** Rovara local AWS service key to IAM prefix. */",
    `export const TEST_ACCESS_SCOPING_SERVICE_KEYS: Readonly<Record<string, string>> = ${stringify(keyToPrefix)};`,
    "",
    "/** Service keys with no reference to read (not an IAM service, or too new for the reference): their actions are signer-only. */",
    `export const TEST_ACCESS_SCOPING_UNMAPPED: readonly string[] = ${stringify(unmapped)};`,
    "",
    "/** Per IAM prefix: the ARN patterns of the resource types name-guarded actions act on, with {{Name}} where the run's name goes and {{Partition}}, {{Region}}, {{AccountId}} tokens. */",
    `export const TEST_ACCESS_SCOPING_NAME_ARNS: Readonly<Record<string, readonly string[]>> = ${stringify(nameArns)};`,
    "",
    "export const TEST_ACCESS_SCOPING: Readonly<Record<string, Readonly<Record<string, readonly string[]>>>> = {",
    ...Object.entries(services).map(([prefix, grouped]) => `  ${stringify(prefix)}: ${stringify(grouped)},`),
    "};",
    "",
  ];
  return lines.join("\n");
}

async function main(argv: readonly string[]): Promise<number> {
  const option = (name: string): string | undefined => {
    const at = argv.indexOf(name);
    return at === -1 ? undefined : argv[at + 1];
  };
  const downloadTo = option("--download");
  if (downloadTo !== undefined) {
    await download(downloadTo);
    return 0;
  }
  const from = option("--from");
  const services = option("--services");
  if (from === undefined || services === undefined) {
    console.error("usage: gen-action-scoping.ts --download <dir> | --from <dir> --services <aws-emulator-services.json> [--check]");
    return 2;
  }
  const text = build(from, services);
  if (argv.includes("--check")) {
    if (readFileSync(OUTPUT, "utf8") === text) return 0;
    console.error(`${OUTPUT} is not what the generator makes from these inputs`);
    return 1;
  }
  writeFileSync(OUTPUT, text);
  return 0;
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) process.exitCode = await main(process.argv.slice(2));
