// Writes the files the customer test account's connect kit is made of, from one source (packages/cloud-contracts/src/test-access-policy.ts), so they cannot drift apart:
//   environments/test-access/cloudformation/rovara-test-access.template.yaml   the CloudFormation template (from rovara-test-access.source.yaml)
//   environments/test-access/terraform/policies/*.json.tftpl                    the Terraform module's policies
//   environments/test-access/policy/*.json                                      the copy-paste policy text, with <PLACEHOLDERS>
//
//   npx tsx scripts/test-access/build-artifacts.ts           write
//   npx tsx scripts/test-access/build-artifacts.ts --check   exit 1 when a file differs from what the source makes (tests/unit/test-access-artifacts.test.ts does the same)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  TEST_ACCESS_CALLBACK_TIMEOUT_SECONDS,
  TEST_ACCESS_TEMPLATE_VERSION,
  buildTestAccessPolicies,
  buildTrustPolicy,
  cloudFormationPolicy,
  renderPolicyTokens,
  terraformPolicyTemplate,
} from "../../packages/cloud-contracts/src/index.js";

const ROOT = "environments/test-access";
const SOURCE = `${ROOT}/cloudformation/rovara-test-access.source.yaml`;
export const GENERATED_HEADER = "# GENERATED by scripts/test-access/build-artifacts.ts from rovara-test-access.source.yaml and packages/cloud-contracts/src/test-access-policy.ts. Do not edit; change the source and run it again.\n";

/** A JSON value as a YAML flow value under `indent` spaces. JSON is YAML, so the document keeps its shape and is easy to read. */
function jsonBlock(value: unknown, indent: number): string {
  const lines = JSON.stringify(value, null, 2).split("\n");
  return lines.map((line, index) => (index === 0 ? line : `${" ".repeat(indent)}${line}`)).join("\n");
}

export function renderTemplate(): string {
  const policies = buildTestAccessPolicies();
  const cleanupPolicy = `  RovaraTestCleanupPolicy:\n    Type: AWS::IAM::ManagedPolicy\n    Properties:\n      Description: "What Rovara's cleanup role may do, inside the boundary: read and delete. Rovara test access."\n      PolicyDocument: ${jsonBlock(cloudFormationPolicy(policies.cleanup), 6)}\n\n`;
  const filled = readFileSync(SOURCE, "utf8")
    .replaceAll("@@VERSION@@", TEST_ACCESS_TEMPLATE_VERSION)
    .replaceAll("@@TIMEOUT@@", String(TEST_ACCESS_CALLBACK_TIMEOUT_SECONDS))
    .replace("@@BOUNDARY@@", jsonBlock(cloudFormationPolicy(policies.boundary), 6))
    .replace("@@ACCESS@@", jsonBlock(cloudFormationPolicy(policies.access), 6))
    .replace("@@CLEANUP_POLICY@@\n", cleanupPolicy);
  const body = filled.replace(/^# The source of[^\n]*\n(?:#[^\n]*\n)*/u, "");
  return GENERATED_HEADER + body;
}

/** Every generated file, by repo-relative path. */
export function renderAll(): Readonly<Record<string, string>> {
  const policies = buildTestAccessPolicies();
  const files: Record<string, string> = { [`${ROOT}/cloudformation/rovara-test-access.template.yaml`]: renderTemplate() };
  files[`${ROOT}/terraform/policies/boundary.json.tftpl`] = terraformPolicyTemplate(policies.boundary);
  files[`${ROOT}/terraform/policies/access.json.tftpl`] = terraformPolicyTemplate(policies.access);
  files[`${ROOT}/terraform/policies/cleanup.json.tftpl`] = terraformPolicyTemplate(policies.cleanup);
  const values = { Partition: "aws", Region: "<REGION>", AccountId: "<ACCOUNT_ID>", BoundaryArn: "arn:aws:iam::<ACCOUNT_ID>:policy/rovara-test-boundary-<EXTERNAL_ID>" };
  const text = (document: unknown): string => `${JSON.stringify(document, null, 2)}\n`;
  files[`${ROOT}/policy/trust-policy.json`] = text(buildTrustPolicy({ principalArn: "<ROVARA_PRINCIPAL_ARN>", externalId: "<EXTERNAL_ID>" }));
  files[`${ROOT}/policy/permissions-boundary.json`] = text(renderPolicyTokens(policies.boundary, values));
  files[`${ROOT}/policy/test-role-access.json`] = text(renderPolicyTokens(policies.access, values));
  files[`${ROOT}/policy/cleanup-role-access.json`] = text(renderPolicyTokens(policies.cleanup, values));
  return files;
}

/** The generated paths in a folder that the source no longer makes (a part count that went down). */
function staleFiles(files: Readonly<Record<string, string>>): string[] {
  const stale: string[] = [];
  for (const folder of [`${ROOT}/terraform/policies`, `${ROOT}/policy`]) {
    for (const name of readdirSync(folder)) {
      const path = `${folder}/${name}`;
      if (/\.(json|tftpl)$/u.test(name) && !(path in files)) stale.push(path);
    }
  }
  return stale;
}

function main(argv: readonly string[]): number {
  const files = renderAll();
  const check = argv.includes("--check");
  let problems = 0;
  for (const [path, content] of Object.entries(files)) {
    let current: string | undefined;
    try {
      current = readFileSync(path, "utf8");
    } catch {
      current = undefined;
    }
    if (current === content) continue;
    if (check) {
      console.error(`${path} differs from what the source makes`);
      problems += 1;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  for (const path of staleFiles(files)) {
    if (check) {
      console.error(`${path} is not made by the source any more`);
      problems += 1;
    } else rmSync(path);
  }
  return problems === 0 ? 0 : 1;
}

if (process.argv[1] !== undefined && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  mkdirSync(join(ROOT, "terraform/policies"), { recursive: true });
  mkdirSync(join(ROOT, "policy"), { recursive: true });
  process.exitCode = main(process.argv.slice(2));
}
