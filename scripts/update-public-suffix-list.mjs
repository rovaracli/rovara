// Regenerates public-suffix-rules.ts of Rovara Code's contracts (vendored since convergence W0-3: run this in Code, then refresh the pin) (the data public-suffix.ts matches against) from the Public Suffix List at one commit.
//
//   node scripts/update-public-suffix-list.mjs <commit-sha>
//
// The commit is a full 40-character SHA of https://github.com/publicsuffix/list, so the module always names exactly what it was built
// from. Run it at a commit no newer than two weeks old: a very recent entry has had no time to be reviewed or reverted.
// The module holds every rule of both sections (ICANN and PRIVATE): `*.s3.amazonaws.com`-style hosting names are suffixes too.
import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";
import { fileURLToPath } from "node:url";

const commit = process.argv[2];
if (!/^[0-9a-f]{40}$/.test(commit ?? "")) {
  console.error("usage: node scripts/update-public-suffix-list.mjs <40-character commit sha of publicsuffix/list>");
  process.exit(2);
}

const response = await fetch(`https://raw.githubusercontent.com/publicsuffix/list/${commit}/public_suffix_list.dat`, { redirect: "error" });
if (!response.ok) {
  console.error(`could not download the list at ${commit}: HTTP ${String(response.status)}`);
  process.exit(1);
}
const text = await response.text();

// A rule is the first whitespace-delimited token of a line that is not blank and not a comment. Non-ASCII rules are stored as punycode,
// the form a DNS name takes.
const rules = new Set();
let section = "";
const sections = new Set();
for (const line of text.split(/\r?\n/)) {
  const marker = /^\/\/ ===(BEGIN|END) (ICANN|PRIVATE) DOMAINS===/.exec(line);
  if (marker !== null) {
    section = marker[1] === "BEGIN" ? marker[2] : "";
    if (marker[1] === "BEGIN") sections.add(marker[2]);
    continue;
  }
  const rule = line.trim().split(/\s+/)[0];
  if (rule === undefined || rule === "" || rule.startsWith("//")) continue;
  if (section === "") throw new Error(`rule ${rule} sits outside the ICANN and PRIVATE sections`);
  const exception = rule.startsWith("!");
  const wildcard = rule.startsWith("*.");
  const name = domainToASCII(rule.slice(exception ? 1 : wildcard ? 2 : 0).toLowerCase());
  if (name === "") throw new Error(`rule ${rule} is not a domain name`);
  rules.add(`${exception ? "!" : wildcard ? "*." : ""}${name}`);
}
if (!sections.has("ICANN") || !sections.has("PRIVATE") || rules.size < 5000) {
  throw new Error(`the list at ${commit} looks wrong: ${String(rules.size)} rules, sections ${[...sections].join(",")}`);
}

const body = [...rules].sort().map((rule) => `  ${JSON.stringify(rule)},`).join("\n");
const module = `// GENERATED by scripts/update-public-suffix-list.mjs: do not edit by hand.
// Source: https://github.com/publicsuffix/list/blob/${commit}/public_suffix_list.dat
// Commit: ${commit}
// Rules: ${String(rules.size)} (ICANN and PRIVATE sections; a leading "*." is a wildcard rule, a leading "!" an exception rule).
// Regenerate: node scripts/update-public-suffix-list.mjs <commit>, at a commit no newer than two weeks old.

const rules = new Set<string>([
${body}
]);
// The set decides what a project may let its machines reach, so nothing at runtime may change it.
for (const method of ["add", "delete", "clear"] as const) {
  Object.defineProperty(rules, method, { value: () => { throw new TypeError("the public suffix list is read-only"); } });
}

export const PUBLIC_SUFFIX_LIST_COMMIT = ${JSON.stringify(commit)};
export const PUBLIC_SUFFIX_RULES: ReadonlySet<string> = Object.freeze(rules);
`;
writeFileSync(fileURLToPath(new URL("../vendor/rovara-code/packages/contracts/src/public-suffix-rules.ts", import.meta.url)), module);
console.log(`wrote vendor/rovara-code/packages/contracts/src/public-suffix-rules.ts: ${String(rules.size)} rules from ${commit}`);
