import {expect,it} from "vitest";
import { auditOperatorId } from "@agentx/cloud-contracts";
import {auditModelPolicyChanged,auditModelPolicyLockSet,auditModelPolicyLockRemoved} from "../../packages/broker/src/audit/events.js";
import {processAuditBatch} from "../../packages/broker/src/audit/appender-handler.js";
import {appendEvent} from "../../packages/broker/src/audit/appender.js";
import {AuditKeyring} from "../../packages/broker/src/audit/keyring.js";
import {readAuditRecords} from "../../packages/broker/src/audit/reader.js";
import {eraseAuditSubject,noLearningToErase} from "../../packages/broker/src/audit/erase.js";
import {TableScopedDynamoDb} from "../support/table-scoped-dynamodb.js";
import {FakeKms} from "../support/fake-kms.js";
import {FakeAuditSqs} from "../support/fake-audit-sqs.js";
const orgId="org_aaaaaaaaaaaaaaaaaaaa",person="a".repeat(64),at="2026-10-30T13:00:00.000Z";
it.each([auditModelPolicyChanged,auditModelPolicyLockSet,auditModelPolicyLockRemoved])("preserves digest-only policy facts through the real appender/reader and erases personal details (%#)",async builder=>{
 const db=new TableScopedDynamoDb(),keyId="arn:aws:kms:us-east-1:123456789012:key/11111111-2222-3333-4444-555555555555",kms=new FakeKms(keyId),sqs=new FakeAuditSqs();
 const now=()=>Date.parse(at),log=()=>{};
 const keyring=new AuditKeyring({documentClient:db.client,keysTable:"keys",kms:kms.client,keyId,now});
 const deps={documentClient:db.client,ledgerTable:"ledger",sealsTable:"seals",keyring,now,log};
 const event=builder({orgId,actor:{kind:"member",id:person},occurredAt:at,occurrence:"request-policy-1",revision:2,policyDigest:"b".repeat(64),previousDigest:"c".repeat(64),stage:"build",mode:"sole_owner_exception"});
 event.details=[{subject:person,fields:{name:"ERASABLE_POLICY_PERSON",email:"private@example.test"}}];
 expect(await processAuditBatch(deps,{Records:[{messageId:"policy-1",body:JSON.stringify(event),attributes:{MessageGroupId:orgId}}]})).toEqual({batchItemFailures:[]});expect(await appendEvent(deps,event)).toMatchObject({result:"duplicate"});
 const before=await readAuditRecords(deps,orgId);
 expect(before.records).toHaveLength(1);expect(before.records[0]!.record.action).toBe(event.action);
 expect(before.records[0]!.record.facts).toEqual(event.facts);
 expect(JSON.stringify(before)).toContain("ERASABLE_POLICY_PERSON");
 const stored=db.find("ledger",row=>String(row.sk).startsWith("SEQ#"));
 expect(JSON.stringify(stored)).not.toContain("ERASABLE_POLICY_PERSON");expect(JSON.stringify(stored)).not.toContain("private@example.test");
 const audit={sqs:sqs.client,queueUrl:"https://sqs.test/intake.fifo",documentClient:db.client,tableName:"state",now,log};
 await eraseAuditSubject({documentClient:db.client,keysTable:"keys",tableName:"state",audit,now,log,purgeExports:async()=>{},eraseLearning:noLearningToErase},{orgId,developerId:person,by:{kind:"operator",id:auditOperatorId("https://staff.test","operator")},reason:"Approved erasure",requestId:"erase-policy-person"});
 const after=await readAuditRecords(deps,orgId);
 expect(after.records[0]!.record).toEqual(before.records[0]!.record);
 expect(JSON.stringify(after)).not.toContain("ERASABLE_POLICY_PERSON");expect(JSON.stringify(after)).not.toContain("private@example.test");
});
