/** The display name of an AWS service id (a key, or a legacy key such as `secretsmanager`); undefined when the table does not know the service. */
export function awsServiceDisplayName(id: string): string | undefined {
  const key = normaliseAwsServiceKey(id);
  return key !== undefined && Object.hasOwn(AWS_SERVICE_DISPLAY_NAMES, key) ? AWS_SERVICE_DISPLAY_NAMES[key] : undefined;
}

/** The display name of a dependency family: `aws:sns` is "SNS". Undefined for a family that is not an AWS service of the table (the caller shows what it showed before). */
export function awsFamilyDisplayName(family: string): string | undefined {
  return family.startsWith("aws:") ? awsServiceDisplayName(family.slice(4)) : undefined;
}
